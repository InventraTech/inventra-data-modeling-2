-- ---------------------------------------------------
-- BACKUP AND RECOVERY
-- ---------------------------------------------------
-- Histórico das execuções de backup/restore (gravado por postgre/backup/*.sh),
-- recuperação de uma linha pela trilha de auditoria e contagem exata por tabela
-- para conferir um restore. Procedimento completo em docs/BACKUP_AND_RECOVERY.md.

-- ---------------------------------------------------
-- TABLE CREATION
-- ---------------------------------------------------

-- TIMESTAMPTZ: o horário vem da máquina que roda o script, não do servidor
CREATE TABLE IF NOT EXISTS tb_backup_history (
	id_backup INTEGER GENERATED BY DEFAULT AS IDENTITY,
	operation VARCHAR(20) NOT NULL,
	status VARCHAR(10) NOT NULL,
	database_name VARCHAR(63) NOT NULL,
	file_name VARCHAR(255) NOT NULL,
	file_size_bytes BIGINT,
	checksum_sha256 CHAR(64),
	started_at TIMESTAMPTZ NOT NULL,
	finished_at TIMESTAMPTZ NOT NULL,
	executed_by VARCHAR(100) NOT NULL DEFAULT CURRENT_USER,
	error_message VARCHAR(1000),
	PRIMARY KEY (id_backup)
);

-- ---------------------------------------------------
-- CHECK CONSTRAINTS
-- ---------------------------------------------------

DO $$
BEGIN
	IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_backuphistory_operation') THEN
		ALTER TABLE tb_backup_history
		ADD CONSTRAINT ck_backuphistory_operation
		CHECK (operation IN ('BACKUP', 'RESTORE'));
	END IF;
END;
$$;

DO $$
BEGIN
	IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_backuphistory_status') THEN
		ALTER TABLE tb_backup_history
		ADD CONSTRAINT ck_backuphistory_status
		CHECK (status IN ('SUCCESS', 'FAILED'));
	END IF;
END;
$$;

-- falha sempre diz o motivo; sucesso nunca tem erro
DO $$
BEGIN
	IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_backuphistory_error') THEN
		ALTER TABLE tb_backup_history
		ADD CONSTRAINT ck_backuphistory_error
		CHECK ((status = 'FAILED') = (error_message IS NOT NULL));
	END IF;
END;
$$;

DO $$
BEGIN
	IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_backuphistory_period') THEN
		ALTER TABLE tb_backup_history
		ADD CONSTRAINT ck_backuphistory_period
		CHECK (finished_at >= started_at);
	END IF;
END;
$$;

DO $$
BEGIN
	IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_backuphistory_checksum') THEN
		ALTER TABLE tb_backup_history
		ADD CONSTRAINT ck_backuphistory_checksum
		CHECK (checksum_sha256 ~ '^[0-9a-f]{64}$');
	END IF;
END;
$$;

-- ---------------------------------------------------
-- INDEX CREATION
-- ---------------------------------------------------

-- vw_backup_status busca a última execução com sucesso de cada operação
CREATE INDEX IF NOT EXISTS idx_backuphistory_operation_finished
ON tb_backup_history (operation, finished_at DESC);

-- ---------------------------------------------------
