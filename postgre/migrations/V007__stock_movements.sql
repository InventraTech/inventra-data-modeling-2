-- ---------------------------------------------------
-- TABLE CREATION
-- ---------------------------------------------------

CREATE TABLE IF NOT EXISTS tb_stock_movement (
	id_movement INTEGER GENERATED BY DEFAULT AS IDENTITY,
	id_batch INTEGER NOT NULL,
	id_user UUID,
	id_requisition INTEGER,
	type VARCHAR(20) NOT NULL,
	reason VARCHAR(20),
	quantity DECIMAL(12,3) NOT NULL,
	balance_after DECIMAL(12,3) NOT NULL,
	created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	PRIMARY KEY (id_movement)
);

-- ---------------------------------------------------
-- FOREIGN KEYS
-- ---------------------------------------------------

DO $$
BEGIN
	IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_movement_batch') THEN
		ALTER TABLE tb_stock_movement
		ADD CONSTRAINT fk_movement_batch
		FOREIGN KEY (id_batch) REFERENCES tb_stock_batch (id_batch)
		ON UPDATE NO ACTION ON DELETE NO ACTION;
	END IF;
END;
$$;

DO $$
BEGIN
	IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_movement_user') THEN
		ALTER TABLE tb_stock_movement
		ADD CONSTRAINT fk_movement_user
		FOREIGN KEY (id_user) REFERENCES tb_user (id_user)
		ON UPDATE NO ACTION ON DELETE NO ACTION;
	END IF;
END;
$$;

DO $$
BEGIN
	IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_movement_requisition') THEN
		ALTER TABLE tb_stock_movement
		ADD CONSTRAINT fk_movement_requisition
		FOREIGN KEY (id_requisition) REFERENCES tb_requisition (id_requisition)
		ON UPDATE NO ACTION ON DELETE NO ACTION;
	END IF;
END;
$$;

-- ---------------------------------------------------
-- CHECK CONSTRAINTS
-- ---------------------------------------------------

DO $$
BEGIN
	IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_movement_type') THEN
		ALTER TABLE tb_stock_movement
		ADD CONSTRAINT ck_movement_type
		CHECK (type IN ('ENTRY', 'WRITE_OFF', 'ADJUSTMENT'));
	END IF;
END;
$$;

-- o motivo só existe (e é obrigatório) na baixa
DO $$
BEGIN
	IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_movement_reason') THEN
		ALTER TABLE tb_stock_movement
		ADD CONSTRAINT ck_movement_reason
		CHECK (
			(type = 'WRITE_OFF' AND reason IN ('USAGE', 'LOSS', 'EXPIRED', 'REQUISITION'))
			OR (type <> 'WRITE_OFF' AND reason IS NULL)
		);
	END IF;
END;
$$;

-- entrada e baixa guardam a quantidade movimentada; o ajuste guarda a diferença, com sinal
DO $$
BEGIN
	IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_movement_quantity') THEN
		ALTER TABLE tb_stock_movement
		ADD CONSTRAINT ck_movement_quantity
		CHECK (
			(type = 'ADJUSTMENT' AND quantity <> 0)
			OR (type <> 'ADJUSTMENT' AND quantity > 0)
		);
	END IF;
END;
$$;

-- ---------------------------------------------------
-- INDEX CREATION
-- ---------------------------------------------------

CREATE INDEX IF NOT EXISTS idx_movement_batch_created_at
ON tb_stock_movement (id_batch, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_movement_user
ON tb_stock_movement (id_user);

CREATE INDEX IF NOT EXISTS idx_movement_requisition
ON tb_stock_movement (id_requisition);

CREATE INDEX IF NOT EXISTS idx_movement_created_at
ON tb_stock_movement (created_at);

-- ---------------------------------------------------
-- PROCEDURE CREATION
-- ---------------------------------------------------

-- os parâmetros novos têm DEFAULT: a chamada antiga, só com lote e quantidade, continua valendo.
-- a assinatura antiga precisa sair antes, senão o CALL com dois argumentos fica ambíguo.
DROP PROCEDURE IF EXISTS sp_register_stock_entry(INTEGER, DECIMAL);

CREATE OR REPLACE PROCEDURE sp_register_stock_entry(
    p_id_batch INTEGER,
    p_quantity DECIMAL(12,3),
    p_id_user UUID DEFAULT NULL
)
LANGUAGE plpgsql
AS
$$
DECLARE
    v_status VARCHAR(20);
    v_balance DECIMAL(12,3);
BEGIN

    IF p_quantity <= 0 THEN
        RAISE EXCEPTION
            'A quantidade de entrada deve ser maior que zero.';
    END IF;

    SELECT status
    INTO v_status
    FROM tb_stock_batch
    WHERE id_batch = p_id_batch
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'Lote % não encontrado.',
            p_id_batch;
    END IF;

    IF v_status IN ('EXPIRED', 'CANCELLED') THEN
        RAISE EXCEPTION
            'Não é possível dar entrada em lote vencido ou cancelado.';
    END IF;

    UPDATE tb_stock_batch
    SET
        current_quantity = current_quantity + p_quantity,
        status = 'ACTIVE'
    WHERE id_batch = p_id_batch
    RETURNING current_quantity INTO v_balance;

    INSERT INTO tb_stock_movement (id_batch, id_user, type, quantity, balance_after)
    VALUES (p_id_batch, p_id_user, 'ENTRY', p_quantity, v_balance);

END;
$$;

DROP PROCEDURE IF EXISTS sp_write_off_stock(INTEGER, DECIMAL);

CREATE OR REPLACE PROCEDURE sp_write_off_stock(
    p_id_batch INTEGER,
    p_quantity DECIMAL(12,3),
    p_id_user UUID DEFAULT NULL,
    p_reason VARCHAR(20) DEFAULT 'USAGE',
    p_id_requisition INTEGER DEFAULT NULL
)
LANGUAGE plpgsql
AS
$$
DECLARE
    v_status VARCHAR(20);
    v_current_quantity DECIMAL(12,3);
    v_reason VARCHAR(20) := COALESCE(p_reason, 'USAGE');
    v_balance DECIMAL(12,3);
BEGIN

    IF p_quantity <= 0 THEN
        RAISE EXCEPTION
            'A quantidade de baixa deve ser maior que zero.';
    END IF;

    IF v_reason NOT IN ('USAGE', 'LOSS', 'EXPIRED', 'REQUISITION') THEN
        RAISE EXCEPTION
            'Motivo de baixa inválido: %.',
            v_reason;
    END IF;

    SELECT status, current_quantity
    INTO v_status, v_current_quantity
    FROM tb_stock_batch
    WHERE id_batch = p_id_batch
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'Lote % não encontrado.',
            p_id_batch;
    END IF;

    IF v_status <> 'ACTIVE' THEN
        RAISE EXCEPTION
            'Só é possível dar baixa em lote ativo.';
    END IF;

    IF v_current_quantity < p_quantity THEN
        RAISE EXCEPTION
            'Saldo insuficiente para dar baixa no lote %.',
            p_id_batch;
    END IF;

    UPDATE tb_stock_batch
    SET
        current_quantity = current_quantity - p_quantity
    WHERE id_batch = p_id_batch
    RETURNING current_quantity INTO v_balance;

    INSERT INTO tb_stock_movement (id_batch, id_user, id_requisition, type, reason, quantity, balance_after)
    VALUES (p_id_batch, p_id_user, p_id_requisition, 'WRITE_OFF', v_reason, p_quantity, v_balance);

END;
$$;
