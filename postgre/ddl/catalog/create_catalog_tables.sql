-- ---------------------------------------------------
-- DATA CATALOG TABLE CREATION
-- ---------------------------------------------------

CREATE TABLE tb_catalog_access_level (
	id_access_level INTEGER GENERATED BY DEFAULT AS IDENTITY,
	code VARCHAR(20) NOT NULL UNIQUE,
	level_rank SMALLINT NOT NULL UNIQUE,
	description VARCHAR(255) NOT NULL,
	audience VARCHAR(255) NOT NULL,
	PRIMARY KEY (id_access_level)
);

CREATE TABLE tb_catalog_table (
	id_catalog_table INTEGER GENERATED BY DEFAULT AS IDENTITY,
	table_name VARCHAR(63) NOT NULL UNIQUE,
	domain VARCHAR(20) NOT NULL DEFAULT 'UNCLASSIFIED',
	description VARCHAR(500),
	business_rules TEXT,
	id_access_level INTEGER NOT NULL,
	data_owner VARCHAR(80),
	created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	PRIMARY KEY (id_catalog_table)
);

CREATE TABLE tb_catalog_column (
	id_catalog_column INTEGER GENERATED BY DEFAULT AS IDENTITY,
	id_catalog_table INTEGER NOT NULL,
	column_name VARCHAR(63) NOT NULL,
	description VARCHAR(500),
	business_rule VARCHAR(500),
	id_access_level INTEGER,
	is_personal_data BOOLEAN NOT NULL DEFAULT false,
	updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	PRIMARY KEY (id_catalog_column),
	UNIQUE (id_catalog_table, column_name)
);

-- ---------------------------------------------------
-- FOREIGN KEYS CREATION
-- ---------------------------------------------------

ALTER TABLE tb_catalog_table
ADD CONSTRAINT fk_catalogtable_access_level
FOREIGN KEY (id_access_level) REFERENCES tb_catalog_access_level (id_access_level)
ON UPDATE NO ACTION ON DELETE NO ACTION;

ALTER TABLE tb_catalog_column
ADD CONSTRAINT fk_catalogcolumn_table
FOREIGN KEY (id_catalog_table) REFERENCES tb_catalog_table (id_catalog_table)
ON UPDATE NO ACTION ON DELETE CASCADE;

ALTER TABLE tb_catalog_column
ADD CONSTRAINT fk_catalogcolumn_access_level
FOREIGN KEY (id_access_level) REFERENCES tb_catalog_access_level (id_access_level)
ON UPDATE NO ACTION ON DELETE NO ACTION;

-- ---------------------------------------------------
-- CHECK CONSTRAINTS
-- ---------------------------------------------------

ALTER TABLE tb_catalog_table
ADD CONSTRAINT ck_catalogtable_domain
CHECK (domain IN ('MASTER_DATA', 'RELATIONSHIP', 'TRANSACTION', 'EVENT', 'AUDIT', 'GOVERNANCE', 'UNCLASSIFIED'));

ALTER TABLE tb_catalog_access_level
ADD CONSTRAINT ck_catalogaccesslevel_rank
CHECK (level_rank > 0);

-- ---------------------------------------------------
-- INDEX CREATION
-- ---------------------------------------------------

CREATE INDEX idx_catalogtable_access_level
ON tb_catalog_table (id_access_level);

CREATE INDEX idx_catalogcolumn_access_level
ON tb_catalog_column (id_access_level);
