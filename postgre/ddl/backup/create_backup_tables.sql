-- ---------------------------------------------------
-- BACKUP HISTORY TABLE CREATION
-- ---------------------------------------------------

-- TIMESTAMPTZ: o horário vem da máquina que roda o script, não do servidor
CREATE TABLE tb_backup_history (
	id_backup INTEGER GENERATED BY DEFAULT AS IDENTITY,
	operation VARCHAR(20) NOT NULL,
	status VARCHAR(10) NOT NULL,
	database_name VARCHAR(63) NOT NULL,
	file_name VARCHAR(255) NOT NULL,
	file_size_bytes BIGINT,
	checksum_sha256 CHAR(64),
	started_at TIMESTAMPTZ NOT NULL,
	finished_at TIMESTAMPTZ NOT NULL,
	executed_by VARCHAR(100) NOT NULL DEFAULT CURRENT_USER,
	error_message VARCHAR(1000),
	PRIMARY KEY (id_backup)
);

-- ---------------------------------------------------
-- CHECK CONSTRAINTS
-- ---------------------------------------------------

ALTER TABLE tb_backup_history
ADD CONSTRAINT ck_backuphistory_operation
CHECK (operation IN ('BACKUP', 'RESTORE'));

ALTER TABLE tb_backup_history
ADD CONSTRAINT ck_backuphistory_status
CHECK (status IN ('SUCCESS', 'FAILED'));

ALTER TABLE tb_backup_history
ADD CONSTRAINT ck_backuphistory_error
CHECK ((status = 'FAILED') = (error_message IS NOT NULL));

ALTER TABLE tb_backup_history
ADD CONSTRAINT ck_backuphistory_period
CHECK (finished_at >= started_at);

ALTER TABLE tb_backup_history
ADD CONSTRAINT ck_backuphistory_checksum
CHECK (checksum_sha256 ~ '^[0-9a-f]{64}$');

-- ---------------------------------------------------
-- INDEX CREATION
-- ---------------------------------------------------

CREATE INDEX idx_backuphistory_operation_finished
ON tb_backup_history (operation, finished_at DESC);
